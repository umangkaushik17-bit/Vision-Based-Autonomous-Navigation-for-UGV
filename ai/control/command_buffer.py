"""Thread-safe, freshness-governed continuous command buffer for high-frequency actuation.

Decouples the planning cycle rate (typically 4-10 Hz) from the high-frequency
actuation rate (typically 20-50 Hz) required by Gazebo diff-drive and hardware controllers.

Key Invariants:
1. Validated Safe Commands: Only safe commands are buffered.
2. Controlled Freshness Window: Commands are held while fresh (e.g. <= 350 ms).
3. Graceful Deceleration: Stale commands smoothly ramp to 0 m/s rather than stepping abruptly.
4. Hard Stale Timeout: Unrefreshed commands older than stale_timeout (e.g. 500 ms) strictly command 0.
5. Immediate Safety Zero: Any safety stop command instantly overrides previous buffer content.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
import math
import threading
import time
from typing import Any, Dict, List, Optional, Tuple
import numpy as np


class DispatchStatus(str, Enum):
    """Status of the command generated by the dispatch buffer."""
    FRESH = "FRESH"
    DECAYING = "DECAYING"
    STALE_STOP = "STALE_STOP"
    SAFETY_STOP = "SAFETY_STOP"
    ZERO_CMD = "ZERO_CMD"


@dataclass
class SafeCommandBufferConfig:
    """Configuration parameters for continuous command dispatching."""
    publish_rate_hz: float = 20.0             # Actuator publication target (Hz)
    freshness_timeout_s: float = 0.35         # Time window where command is fully fresh (s)
    stale_timeout_s: float = 0.50             # Absolute timeout beyond which output is hard zero (s)
    max_deceleration_mps2: float = 1.50       # Controlled deceleration during decay phase (m/s^2)
    max_angular_accel_radps2: float = 2.0     # Controlled angular deceleration during decay (rad/s^2)
    max_linear_vel_mps: float = 1.50          # Vehicle upper velocity clamp
    min_linear_vel_mps: float = -0.50         # Vehicle lower velocity clamp (supports reverse)
    max_angular_vel_radps: float = 1.50       # Vehicle angular velocity clamp

    def __post_init__(self) -> None:
        if self.publish_rate_hz <= 0.0:
            raise ValueError(f"publish_rate_hz must be positive, got {self.publish_rate_hz}")
        if self.freshness_timeout_s <= 0.0:
            raise ValueError(f"freshness_timeout_s must be positive, got {self.freshness_timeout_s}")
        if self.stale_timeout_s < self.freshness_timeout_s:
            raise ValueError(
                f"stale_timeout_s ({self.stale_timeout_s}) must be >= freshness_timeout_s ({self.freshness_timeout_s})"
            )


@dataclass
class BufferedCommand:
    """Internal representation of a buffered velocity command."""
    linear_v: float = 0.0
    angular_w: float = 0.0
    timestamp_s: Optional[float] = None
    is_safe: bool = True
    source: str = "INIT"
    reason: str = "Initialized"


class SafeCommandBuffer:
    """Thread-safe buffer providing continuous, validated velocity commands."""

    def __init__(self, config: Optional[SafeCommandBufferConfig] = None) -> None:
        self.config = config or SafeCommandBufferConfig()
        self._lock = threading.Lock()

        # Active command state
        self._cmd = BufferedCommand()
        self._last_dispatched_v: float = 0.0
        self._last_dispatched_w: float = 0.0
        self._last_dispatch_time_s: Optional[float] = None

        # Telemetry & Diagnostics
        self._dispatch_count: int = 0
        self._fresh_count: int = 0
        self._decay_count: int = 0
        self._stale_count: int = 0
        self._safety_stop_count: int = 0
        self._gaps_ms: List[float] = []
        self._ages_ms: List[float] = []

    def set_command(
        self,
        linear_v: float,
        angular_w: float,
        timestamp_s: float,
        is_safe: bool = True,
        source: str = "PLANNER",
        reason: str = "Nominal",
    ) -> None:
        """Store a new validated command from the local planner or safety layer."""
        with self._lock:
            # Clamp commanded values within physical constraints
            v = float(np.clip(linear_v, self.config.min_linear_vel_mps, self.config.max_linear_vel_mps))
            w = float(np.clip(angular_w, -self.config.max_angular_vel_radps, self.config.max_angular_vel_radps))

            if not (math.isfinite(v) and math.isfinite(w)):
                v = 0.0
                w = 0.0
                is_safe = False
                reason = "NaN or Inf commanded; safety clamp engaged"

            if not is_safe:
                v = 0.0
                w = 0.0

            self._cmd = BufferedCommand(
                linear_v=v,
                angular_w=w,
                timestamp_s=float(timestamp_s),
                is_safe=bool(is_safe),
                source=str(source),
                reason=str(reason),
            )

    def emergency_stop(self, timestamp_s: float, reason: str = "Emergency Stop") -> None:
        """Instantly zero the command buffer with safety override."""
        with self._lock:
            self._cmd = BufferedCommand(
                linear_v=0.0,
                angular_w=0.0,
                timestamp_s=float(timestamp_s),
                is_safe=False,
                source="SAFETY_OVERRIDE",
                reason=str(reason),
            )
            self._last_dispatched_v = 0.0
            self._last_dispatched_w = 0.0

    def get_dispatch_command(
        self,
        current_time_s: float,
    ) -> Tuple[float, float, DispatchStatus, Dict[str, Any]]:
        """Compute the instantaneous command to dispatch to the actuator/Gazebo.

        Returns:
            Tuple of (dispatched_v, dispatched_w, status, diagnostics)
        """
        with self._lock:
            self._dispatch_count += 1
            now = float(current_time_s)

            # Record dispatch gap
            if self._last_dispatch_time_s is not None:
                gap_ms = (now - self._last_dispatch_time_s) * 1000.0
                if gap_ms >= 0.0:
                    self._gaps_ms.append(gap_ms)
                    if len(self._gaps_ms) > 1000:
                        self._gaps_ms.pop(0)

            self._last_dispatch_time_s = now

            cmd = self._cmd
            command_age_s = max(0.0, now - cmd.timestamp_s) if cmd.timestamp_s is not None else 999.0
            self._ages_ms.append(command_age_s * 1000.0)
            if len(self._ages_ms) > 1000:
                self._ages_ms.pop(0)

            # 1. Safety Invariant: If marked unsafe, hard zero immediately
            if not cmd.is_safe:
                self._safety_stop_count += 1
                self._last_dispatched_v = 0.0
                self._last_dispatched_w = 0.0
                return 0.0, 0.0, DispatchStatus.SAFETY_STOP, {
                    "age_ms": round(command_age_s * 1000.0, 2),
                    "reason": cmd.reason,
                    "source": cmd.source,
                }

            # 2. If command is naturally zero
            if abs(cmd.linear_v) < 1e-4 and abs(cmd.angular_w) < 1e-4:
                self._last_dispatched_v = 0.0
                self._last_dispatched_w = 0.0
                return 0.0, 0.0, DispatchStatus.ZERO_CMD, {
                    "age_ms": round(command_age_s * 1000.0, 2),
                    "reason": "Command is zero",
                    "source": cmd.source,
                }

            # 3. Fresh Command (< freshness_timeout_s)
            if command_age_s <= self.config.freshness_timeout_s:
                self._fresh_count += 1
                self._last_dispatched_v = cmd.linear_v
                self._last_dispatched_w = cmd.angular_w
                return cmd.linear_v, cmd.angular_w, DispatchStatus.FRESH, {
                    "age_ms": round(command_age_s * 1000.0, 2),
                    "reason": "Fresh valid command",
                    "source": cmd.source,
                }

            # 4. Decaying Stale Command (freshness_timeout_s < age <= stale_timeout_s)
            elif command_age_s <= self.config.stale_timeout_s:
                self._decay_count += 1
                # Smoothly ramp velocity to 0
                decay_fraction = (self.config.stale_timeout_s - command_age_s) / max(
                    1e-4, (self.config.stale_timeout_s - self.config.freshness_timeout_s)
                )
                decay_fraction = float(np.clip(decay_fraction, 0.0, 1.0))
                dispatched_v = cmd.linear_v * decay_fraction
                dispatched_w = cmd.angular_w * decay_fraction

                self._last_dispatched_v = dispatched_v
                self._last_dispatched_w = dispatched_w
                return dispatched_v, dispatched_w, DispatchStatus.DECAYING, {
                    "age_ms": round(command_age_s * 1000.0, 2),
                    "decay_fraction": round(decay_fraction, 3),
                    "reason": "Decaying towards zero due to delayed planner update",
                    "source": cmd.source,
                }

            # 5. Stale Timeout Reached (> stale_timeout_s)
            else:
                self._stale_count += 1
                self._last_dispatched_v = 0.0
                self._last_dispatched_w = 0.0
                return 0.0, 0.0, DispatchStatus.STALE_STOP, {
                    "age_ms": round(command_age_s * 1000.0, 2),
                    "reason": f"Stale timeout exceeded ({command_age_s:.3f}s > {self.config.stale_timeout_s:.3f}s)",
                    "source": cmd.source,
                }

    def get_metrics(self) -> Dict[str, Any]:
        """Retrieve aggregated timing, gap, and dispatch statistics."""
        with self._lock:
            gaps = np.array(self._gaps_ms) if self._gaps_ms else np.array([0.0])
            ages = np.array(self._ages_ms) if self._ages_ms else np.array([0.0])
            return {
                "total_dispatches": self._dispatch_count,
                "fresh_count": self._fresh_count,
                "decay_count": self._decay_count,
                "stale_count": self._stale_count,
                "safety_stop_count": self._safety_stop_count,
                "gap_mean_ms": round(float(np.mean(gaps)), 2),
                "gap_p50_ms": round(float(np.percentile(gaps, 50)), 2),
                "gap_p95_ms": round(float(np.percentile(gaps, 95)), 2),
                "gap_max_ms": round(float(np.max(gaps)), 2),
                "age_mean_ms": round(float(np.mean(ages)), 2),
                "age_max_ms": round(float(np.max(ages)), 2),
            }

    def reset(self) -> None:
        """Reset internal metrics and state."""
        with self._lock:
            self._cmd = BufferedCommand()
            self._last_dispatched_v = 0.0
            self._last_dispatched_w = 0.0
            self._last_dispatch_time_s = None
            self._dispatch_count = 0
            self._fresh_count = 0
            self._decay_count = 0
            self._stale_count = 0
            self._safety_stop_count = 0
            self._gaps_ms.clear()
            self._ages_ms.clear()
